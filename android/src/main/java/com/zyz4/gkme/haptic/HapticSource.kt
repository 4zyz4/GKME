package com.zyz4.gkme.haptic

/**
 * HE（RichTap 动态效果）的发送来源。
 *
 * 手机线性马达只有一个 `HapticPlayer`，但自适应扳机、音频到震动、游戏震动、按钮震动四条
 * 通路都会向它投递效果。若没有仲裁，它们会交替 `start()`，马达收到互相交错的幅度/频率，
 * 表现为“震动混乱”。
 *
 * 这里给每条通路一个优先级：同一时刻只允许一个来源驱动；高优先级可抢占低优先级，低优先级
 * 在更高来源播放期间被**静默**（不发效果，也不回退系统震动）。优先级按需求排列：
 * 自适应扳机 > 音频到震动 > 游戏震动 > 按钮震动。
 */
enum class HapticSource(val priority: Int) {
    /** 按键自定义震动 / 系统触感替换。 */
    BUTTON(0),

    /** PC 游戏 rumble（强/弱马达）。 */
    GAME_RUMBLE(1),

    /** 语音线圈 PCM（音频到震动）。 */
    AUDIO(2),

    /** 自适应扳机转震动。 */
    ADAPTIVE_TRIGGER(3),
}
